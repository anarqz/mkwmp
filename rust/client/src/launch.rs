//! The probe's `mkwmp.toml`, and starting the game.

use crate::config::ClientConfig;
use std::path::{Path, PathBuf};
use std::process::{Child, Command};

/// What the probe reads (native/probe/src/config.c): the lobby, the name, how
/// to reach this launcher's local API, and the ticket once seated.
pub struct ProbeConfig<'a> {
    pub lobby: &'a str,
    pub launcher: &'a str,
    pub launcher_token: &'a str,
    pub ticket: Option<&'a str>,
}

pub fn probe_toml(cfg: &ClientConfig, p: &ProbeConfig) -> String {
    let mut s = String::new();
    s.push_str("# Generated by the mkwmp launcher. Do not edit; edit client.toml.\n");
    s.push_str(&format!("server = \"{}\"\n", p.lobby));
    s.push_str(&format!("name = \"{}\"\n", cfg.name));
    s.push_str(&format!("launcher = \"{}\"\n", p.launcher));
    s.push_str(&format!("launcher_token = \"{}\"\n", p.launcher_token));
    if let Some(t) = p.ticket {
        s.push_str(&format!("ticket = \"{t}\"\n"));
    }
    if cfg.slot != 1 {
        s.push_str(&format!("slot = {}\n", cfg.slot));
    }
    s
}

/// Write `<game>/mkwmp.toml` atomically, so the probe never reads half a file.
pub fn write_probe_toml(game_dir: &Path, contents: &str) -> std::io::Result<PathBuf> {
    let path = game_dir.join("mkwmp.toml");
    let tmp = game_dir.join("mkwmp.toml.tmp");
    std::fs::write(&tmp, contents)?;
    std::fs::rename(&tmp, &path)?;
    Ok(path)
}

/// Start mkw.exe in the game directory.
pub fn spawn_game(game_dir: &Path) -> std::io::Result<Child> {
    Command::new(game_dir.join("mkw.exe")).arg("--play").current_dir(game_dir).spawn()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::SeatMode;

    fn cfg(slot: u8) -> ClientConfig {
        ClientConfig {
            server: "https://mkw.example".into(),
            name: "Ana".into(),
            pin: String::new(),
            friends: vec![],
            game: "C:/game".into(),
            launch: true,
            seat: SeatMode::Start,
            local_port: 47820,
            update: true,
            slot,
        }
    }

    #[test]
    fn probe_toml_carries_everything_the_probe_reads() {
        let p = ProbeConfig { lobby: "mkwlb.example:8905", launcher: "127.0.0.1:47820", launcher_token: "abc", ticket: Some("mkw1.x.y") };
        let t = probe_toml(&cfg(2), &p);
        for line in [
            "server = \"mkwlb.example:8905\"",
            "name = \"Ana\"",
            "launcher = \"127.0.0.1:47820\"",
            "launcher_token = \"abc\"",
            "ticket = \"mkw1.x.y\"",
            "slot = 2",
        ] {
            assert!(t.contains(line), "{line} in {t}");
        }
        let p = ProbeConfig { ticket: None, ..p };
        let t = probe_toml(&cfg(1), &p);
        assert!(!t.contains("ticket") && !t.contains("slot"));
    }

    #[test]
    fn write_probe_toml_replaces_the_file() {
        let dir = std::env::temp_dir().join("mkwmp_launch_test");
        std::fs::create_dir_all(&dir).unwrap();
        write_probe_toml(&dir, "a = 1\n").unwrap();
        let p = write_probe_toml(&dir, "b = 2\n").unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "b = 2\n");
    }
}
