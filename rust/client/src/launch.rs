//! The probe's `mkwmp.toml`, and starting the game.

use crate::config::ClientConfig;
use std::path::{Path, PathBuf};
use std::process::{Child, Command};

/// What the probe reads (native/probe/src/config.c): the lobby, the name, how
/// to reach this launcher's local API, and the ticket once seated.
pub struct ProbeConfig<'a> {
    pub lobby: &'a str,
    pub launcher: &'a str,
    pub launcher_token: &'a str,
    pub ticket: Option<&'a str>,
    /// The lobby host's voice relay port (seat status `voicePort`; 0 = off).
    pub voice_port: u16,
}

pub fn probe_toml(cfg: &ClientConfig, p: &ProbeConfig) -> String {
    let mut s = String::new();
    s.push_str("# Generated by the mkwmp launcher. Do not edit; edit client.toml.\n");
    s.push_str(&format!("server = \"{}\"\n", p.lobby));
    s.push_str(&format!("name = \"{}\"\n", cfg.name));
    s.push_str(&format!("launcher = \"{}\"\n", p.launcher));
    s.push_str(&format!("launcher_token = \"{}\"\n", p.launcher_token));
    s.push_str(&format!("voice_port = {}\n", p.voice_port));
    if let Some(t) = p.ticket {
        s.push_str(&format!("ticket = \"{t}\"\n"));
    }
    if cfg.slot != 1 {
        s.push_str(&format!("slot = {}\n", cfg.slot));
    }
    s
}

/// Write `<game>/mkwmp.toml` atomically, so the probe never reads half a file.
pub fn write_probe_toml(game_dir: &Path, contents: &str) -> std::io::Result<PathBuf> {
    let path = game_dir.join("mkwmp.toml");
    let tmp = game_dir.join("mkwmp.toml.tmp");
    std::fs::write(&tmp, contents)?;
    std::fs::rename(&tmp, &path)?;
    Ok(path)
}

/// The lobby certificate the probe trusts, next to `mkwmp.toml` (the
/// probe's default `lobby_ca` name). Without it the probe trusts its
/// built-in certificate.
pub const LOBBY_CA: &str = "mkwmp-lobby-ca.pem";

/// Write the server's lobby certificate for the probe, or remove the file
/// when the server has none.
pub fn write_lobby_ca(game_dir: &Path, pem: Option<&str>) -> std::io::Result<()> {
    let path = game_dir.join(LOBBY_CA);
    match pem {
        Some(pem) => {
            let tmp = game_dir.join(format!("{LOBBY_CA}.tmp"));
            std::fs::write(&tmp, pem)?;
            std::fs::rename(&tmp, &path)
        }
        None => match std::fs::remove_file(&path) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        },
    }
}

/// Start mkw.exe in the game directory.
/// Start the game: `launch_command` when set (e.g. through Proton on the Steam
/// Deck, where the launcher itself is the Steam shortcut), else `mkw.exe --play`.
/// The command runs in the game folder (`sh -c` on Unix, `cmd /C` on Windows).
pub fn spawn_game(game_dir: &Path, launch_command: &str) -> std::io::Result<Child> {
    let cmd = launch_command.trim();
    if cmd.is_empty() {
        return Command::new(game_dir.join("mkw.exe")).arg("--play").current_dir(game_dir).spawn();
    }
    #[cfg(unix)]
    let mut c = {
        let mut c = Command::new("sh");
        c.arg("-c").arg(cmd);
        c
    };
    #[cfg(windows)]
    let mut c = {
        let mut c = Command::new("cmd");
        c.arg("/C").arg(cmd);
        c
    };
    c.current_dir(game_dir).spawn()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::SeatMode;

    fn cfg(slot: u8) -> ClientConfig {
        ClientConfig {
            server: "https://mkw.example".into(),
            name: "Ana".into(),
            pin: String::new(),
            game: "C:/game".into(),
            launch: true,
            seat: SeatMode::Start,
            local_port: 47820,
            update: true,
            slot,
            launch_command: String::new(),
            background: Default::default(),
            voice: Default::default(),
        }
    }

    #[test]
    fn probe_toml_carries_everything_the_probe_reads() {
        let p = ProbeConfig { lobby: "mkwlb.example:8905", launcher: "127.0.0.1:47820", launcher_token: "abc", ticket: Some("mkw1.x.y"), voice_port: 8907 };
        let t = probe_toml(&cfg(2), &p);
        for line in [
            "server = \"mkwlb.example:8905\"",
            "name = \"Ana\"",
            "launcher = \"127.0.0.1:47820\"",
            "launcher_token = \"abc\"",
            "ticket = \"mkw1.x.y\"",
            "slot = 2",
            "voice_port = 8907",
        ] {
            assert!(t.contains(line), "{line} in {t}");
        }
        let p = ProbeConfig { ticket: None, ..p };
        let t = probe_toml(&cfg(1), &p);
        assert!(!t.contains("ticket") && !t.contains("slot"));
    }

    #[test]
    fn write_probe_toml_replaces_the_file() {
        let dir = std::env::temp_dir().join("mkwmp_launch_test");
        std::fs::create_dir_all(&dir).unwrap();
        write_probe_toml(&dir, "a = 1\n").unwrap();
        let p = write_probe_toml(&dir, "b = 2\n").unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "b = 2\n");
    }

    #[test]
    fn lobby_ca_follows_the_server() {
        let dir = std::env::temp_dir().join(format!("mkwmp-ca-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        write_lobby_ca(&dir, Some("-----BEGIN CERTIFICATE-----\n")).unwrap();
        assert!(dir.join(LOBBY_CA).exists());
        write_lobby_ca(&dir, None).unwrap();
        assert!(!dir.join(LOBBY_CA).exists());
        write_lobby_ca(&dir, None).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
