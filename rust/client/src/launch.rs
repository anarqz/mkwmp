//! Generate the probe's `mkwmp.toml` and launch the game.

use crate::config::ClientConfig;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The `mkwmp.toml` the probe reads, built from the client config + ticket.
pub fn probe_toml(cfg: &ClientConfig, ticket: &str) -> String {
    let mut s = String::new();
    s.push_str("# Generated by the mkwmp client. Do not edit; edit client.toml.\n");
    s.push_str(&format!("server = \"{}\"\n", cfg.npln_endpoint()));
    s.push_str(&format!("name = \"{}\"\n", cfg.name));
    s.push_str(&format!("ticket = \"{ticket}\"\n"));
    if cfg.slot != 1 {
        s.push_str(&format!("slot = {}\n", cfg.slot));
    }
    s
}

pub fn write_probe_toml(game_dir: &Path, contents: &str) -> std::io::Result<PathBuf> {
    let path = game_dir.join("mkwmp.toml");
    std::fs::write(&path, contents)?;
    Ok(path)
}

/// Launch mkw.exe in the game directory and wait for it to exit (we hold the
/// seat for the whole session).
pub fn run_game(game_dir: &Path) -> std::io::Result<std::process::ExitStatus> {
    Command::new(game_dir.join("mkw.exe"))
        .arg("--play")
        .current_dir(game_dir)
        .status()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> ClientConfig {
        toml::from_str::<ClientConfig>(
            "server=\"10.0.0.5:7000\"\nname=\"Ana\"\ngame=\"C:/game\"\nslot=2\n",
        )
        .unwrap()
    }

    #[test]
    fn probe_toml_carries_endpoint_name_ticket_and_slot() {
        let t = probe_toml(&cfg(), "seat-00000001");
        assert!(t.contains("server = \"10.0.0.5:8905\"")); // NPLN port, not seat port
        assert!(t.contains("name = \"Ana\""));
        assert!(t.contains("ticket = \"seat-00000001\""));
        assert!(t.contains("slot = 2"));
    }

    #[test]
    fn slot_one_is_omitted() {
        let mut c = cfg();
        c.slot = 1;
        assert!(!probe_toml(&c, "t").contains("slot"));
    }

    #[test]
    fn write_probe_toml_creates_the_file() {
        let dir = std::env::temp_dir();
        let p = write_probe_toml(&dir, "x = 1\n").unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "x = 1\n");
    }
}
