//! Generate the probe's `mkwmp.toml` and launch the game.

use crate::config::ClientConfig;
use std::path::{Path, PathBuf};
use std::process::{Child, Command};

/// The `mkwmp.toml` the probe reads: the lobby endpoint, name and ticket.
pub fn probe_toml(cfg: &ClientConfig, lobby: &str, ticket: &str) -> String {
    let mut s = String::new();
    s.push_str("# Generated by the mkwmp launcher. Do not edit; edit client.toml.\n");
    s.push_str(&format!("server = \"{lobby}\"\n"));
    s.push_str(&format!("name = \"{}\"\n", cfg.name));
    s.push_str(&format!("ticket = \"{ticket}\"\n"));
    if cfg.slot != 1 {
        s.push_str(&format!("slot = {}\n", cfg.slot));
    }
    s
}

pub fn write_probe_toml(game_dir: &Path, contents: &str) -> std::io::Result<PathBuf> {
    let path = game_dir.join("mkwmp.toml");
    std::fs::write(&path, contents)?;
    Ok(path)
}

/// Start mkw.exe in the game directory. MKWMP_NO_FIBER=1 works around a
/// mkw-recomp 0.1.10 abort on the online path (until the probe defaults it).
pub fn spawn_game(game_dir: &Path) -> std::io::Result<Child> {
    let mut cmd = Command::new(game_dir.join("mkw.exe"));
    cmd.arg("--play").current_dir(game_dir);
    if std::env::var_os("MKWMP_NO_FIBER").is_none() {
        cmd.env("MKWMP_NO_FIBER", "1");
    }
    cmd.spawn()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg(slot: u8) -> ClientConfig {
        ClientConfig {
            server: "https://mkw.example".into(),
            name: "Ana".into(),
            friends: vec![],
            game: "C:/game".into(),
            launch: true,
            slot,
        }
    }

    #[test]
    fn probe_toml_carries_lobby_name_ticket_and_slot() {
        let t = probe_toml(&cfg(2), "203.0.113.5:8905", "mkw1.abc.def");
        assert!(t.contains("server = \"203.0.113.5:8905\""));
        assert!(t.contains("name = \"Ana\""));
        assert!(t.contains("ticket = \"mkw1.abc.def\""));
        assert!(t.contains("slot = 2"));
        assert!(!probe_toml(&cfg(1), "h:1", "t").contains("slot"));
    }

    #[test]
    fn write_probe_toml_creates_the_file() {
        let dir = std::env::temp_dir();
        let p = write_probe_toml(&dir, "x = 1\n").unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "x = 1\n");
    }
}
