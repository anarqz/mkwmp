#!/usr/bin/env python3
"""Generate a full-forwarder winmm.def and a renamed copy of the real winmm.

A proxy winmm.dll in the game folder is loaded in place of System32's for EVERY module in the
process that imports winmm by name -- including the Intel/NVIDIA GPU driver DLLs, which import
timeGetDevCaps etc. So our proxy must re-export every function the real winmm exports, each as a
forwarder to a renamed copy (winmm_host.dll) that we place alongside it.

    python gen_def.py                      # writes src/winmm.def, build/winmm_host.dll
"""
import pathlib
import shutil
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
REAL = pathlib.Path(r"C:\Windows\System32\winmm.dll")
HOST_NAME = "winmm_host"   # forward target module (renamed real winmm)
DEF_PATH = HERE / "src" / "winmm.def"
HOST_COPY = HERE / "build" / f"{HOST_NAME}.dll"


def exports(path):
    d = path.read_bytes()
    pe = struct.unpack_from("<I", d, 0x3c)[0]
    opt = pe + 24
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    osz = struct.unpack_from("<H", d, pe + 20)[0]
    secs = [struct.unpack_from("<IIII", d, opt + osz + 40 * i + 8) for i in range(nsec)]

    def r2o(rva):
        for vs, va, rs, ra in secs:
            if va <= rva < va + max(vs, rs):
                return rva - va + ra
        return None

    er = struct.unpack_from("<I", d, opt + 112)[0]
    o = r2o(er)
    base = struct.unpack_from("<I", d, o + 16)[0]
    nfuncs, nnames = struct.unpack_from("<II", d, o + 20)
    addr_rva, name_rva, ord_rva = struct.unpack_from("<III", d, o + 28)
    # name -> ordinal
    out = []
    for i in range(nnames):
        nr = struct.unpack_from("<I", d, r2o(name_rva) + 4 * i)[0]
        name = d[r2o(nr):d.index(b"\0", r2o(nr))].decode()
        ordinal = struct.unpack_from("<H", d, r2o(ord_rva) + 2 * i)[0] + base
        out.append((name, ordinal))
    return out


def main():
    if not REAL.exists():
        sys.exit(f"real winmm not found at {REAL}")
    exps = exports(REAL)
    HOST_COPY.parent.mkdir(exist_ok=True)
    shutil.copy2(REAL, HOST_COPY)

    lines = ["; AUTO-GENERATED by gen_def.py -- forwards all winmm exports to winmm_host.dll",
             "LIBRARY winmm", "EXPORTS"]
    for name, ordinal in sorted(exps, key=lambda x: x[1]):
        lines.append(f"    {name}={HOST_NAME}.{name} @{ordinal}")
    DEF_PATH.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {DEF_PATH} ({len(exps)} forwarders)")
    print(f"copied real winmm -> {HOST_COPY}")


if __name__ == "__main__":
    main()
